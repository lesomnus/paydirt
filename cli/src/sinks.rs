use crate::Result;
use heck::ToSnakeCase;
use quote::ToTokens;
use serde_json::Value;
use std::{collections::BTreeMap, fmt::Write, fs, path::Path};
use syn::{Item, TraitItem};

fn ident(s: &str) -> String {
    match s {
        "self" | "super" | "Self" | "crate" => format!("{s}_"),
        _ => format!("r#{s}"),
    }
}
fn module(path: &str) -> String {
    path.split('.').map(ident).collect::<Vec<_>>().join("::")
}
// The Connect generator resolves nested messages and externally provided types such as
// google.protobuf.Empty. Use the same Rust paths in the operator and in Core's typed calls.
#[derive(Default)]
struct RpcTypes {
    request: Option<syn::Path>,
    response: Option<syn::Path>,
}
impl syn::visit_mut::VisitMut for RpcTypes {
    fn visit_path_segment_mut(&mut self, segment: &mut syn::PathSegment) {
        let destination = match segment.ident.to_string().as_str() {
            "ServiceRequest" | "InboundStream" => Some(&mut self.request),
            "Encodable" => Some(&mut self.response),
            _ => None,
        };
        if let Some(slot) = destination
            && let syn::PathArguments::AngleBracketed(args) = &segment.arguments
            && let Some(path) = args.args.iter().find_map(|arg| match arg {
                syn::GenericArgument::Type(syn::Type::Path(ty)) => Some(&ty.path),
                _ => None,
            })
        {
            *slot = Some(path.clone());
        }
        syn::visit_mut::visit_path_segment_mut(self, segment);
    }
}
fn message_path(path: &syn::Path, proto: &str) -> String {
    let segments: Vec<_> = path.segments.iter().map(|s| s.ident.to_string()).collect();
    if segments.starts_with(&["crate".into(), "proto".into()]) {
        return format!(
            "{proto}::{}",
            segments[2..]
                .iter()
                .map(|s| ident(s.trim_start_matches("r#")))
                .collect::<Vec<_>>()
                .join("::")
        );
    }
    path.to_token_stream().to_string()
}
pub fn generate(work: &Path) -> Result<()> {
    let root = work.join("generated/storage");
    let policies: BTreeMap<String, Value> =
        serde_json::from_slice(&fs::read(root.join("policies.json"))?)?;
    if policies.is_empty() {
        return resource_providers(work, &root);
    }
    fs::write(
        root.join("intercept.rs"),
        include_str!("../templates/intercept.rs"),
    )?;
    let mut out = String::from(
        "// @generated by paydirt.\n#[path=\"intercept.rs\"] pub mod intercept;\nuse crate::transport::Database;\nuse ::connectrpc::{RequestContext, Response, Router, ServiceRequest, ServiceResult};\n",
    );
    let mut hooks = BTreeMap::new();
    for entry in fs::read_dir(work.join("generated/services"))? {
        let path = entry?.path();
        let Some(file) = path
            .file_name()
            .and_then(|n| n.to_str())
            .filter(|n| n.ends_with(".__layers.rs"))
        else {
            continue;
        };
        let package = file.strip_suffix(".__layers.rs").unwrap();
        for item in syn::parse_file(&fs::read_to_string(&path)?)?.items {
            if let Item::Trait(t) = item {
                hooks.insert((package.to_string(), t.ident.to_string()), t);
            }
        }
    }
    let mut next_methods = String::new();
    let mut adapters = String::new();
    let mut commands = String::new();
    let mut layers = String::new();
    let mut mount = String::new();
    // Read resources have service contracts but no ORM entity or SQL sink. Their
    // provider owns filtering, pagination and authorization of each snapshot.
    let descriptor: Value = serde_json::from_slice(&fs::read(work.join("resolved.json"))?)?;
    for file in descriptor["file"].as_array().ok_or("missing files")? {
        let package = file["package"].as_str().unwrap_or_default();
        let source = file["name"]
            .as_str()
            .ok_or("unnamed descriptor file")?
            .trim_end_matches(".proto")
            .replace('/', ".");
        for service in file["service"].as_array().into_iter().flatten() {
            let name = service["name"].as_str().ok_or("unnamed service")?;
            let Some(hook) = hooks.get(&(source.clone(), format!("{name}Layer"))) else {
                continue;
            };
            let svc = format!("crate::services::{}::{name}", module(package));
            writeln!(
                out,
                "impl<N:{svc}> {svc}Layer<N> for crate::storage::intercept::Layer {{"
            )?;
            for item in &hook.items {
                let TraitItem::Fn(f) = item else { continue };
                let fun = &f.sig.ident;
                let rpc = service["method"]
                    .as_array()
                    .ok_or("missing RPC list")?
                    .iter()
                    .find(|m| {
                        m["name"].as_str().is_some_and(|n| {
                            n.to_snake_case() == fun.to_string().trim_start_matches("r#")
                        })
                    })
                    .ok_or("missing interceptor RPC")?;
                let action = format!("/{package}.{name}/{}", rpc["name"].as_str().unwrap());
                let sig = crate::layers::concrete_signature(f.sig.clone()).to_token_stream();
                let mut types = RpcTypes::default();
                syn::visit_mut::VisitMut::visit_signature_mut(&mut types, &mut f.sig.clone());
                let output = message_path(
                    &types.response.ok_or("missing interceptor output")?,
                    "crate::proto",
                );
                let Some(syn::FnArg::Typed(arg)) = f.sig.inputs.last() else {
                    return Err("missing RPC argument".into());
                };
                let arg = arg.pat.to_token_stream();
                let input = if rpc["clientStreaming"] == true {
                    format!("let {arg}=call.stream_input({arg});")
                } else {
                    format!("call.receive({arg}.bytes())?;")
                };
                let finish = if rpc["serverStreaming"] == true {
                    "stream"
                } else {
                    "unary"
                };
                writeln!(
                    out,
                    "{sig} {{async move {{let mut call=self.enter({action:?},ctx)?; {input}let reply=next.{fun}(call.ctx.clone(),{arg}).await; call.{finish}::<{output},_>(reply)}}}}"
                )?;
            }
            writeln!(out, "}}")?;
        }
        for message in file["messageType"].as_array().into_iter().flatten() {
            if message["options"].get("[payday.resource]").is_none() {
                continue;
            }
            let short = message["name"]
                .as_str()
                .ok_or("missing read resource name")?;
            let svc = format!("crate::services::{}::{short}Service", module(package));
            let provider = format!("{}_{}", package.replace('.', "__"), short).to_snake_case();
            writeln!(
                layers,
                "fn {provider}(&self) -> impl {svc} {{ {svc}Unimplemented }}"
            )?;
            writeln!(
                mount,
                "let router={svc}Ext::register(::std::sync::Arc::new({svc}Overlay{{next:layers.{provider}(),layer:interceptors.clone()}}),router);"
            )?;
        }
    }
    for (name, policy) in policies {
        let methods = policy["methods"].as_object().ok_or("missing methods")?;
        if methods.is_empty() {
            continue;
        }
        let (package, short) = name
            .rsplit_once('.')
            .ok_or("expected application package")?;
        let hook_name = format!("{short}ServiceLayer");
        let mut available = hooks
            .iter()
            .filter(|((file, ty), _)| ty == &hook_name && file.starts_with(&format!("{package}.")));
        let service_hooks = &available.next().ok_or("missing generated layer")?.1;
        if available.next().is_some() {
            return Err(format!("ambiguous generated layer for {name}").into());
        }
        let mut types = BTreeMap::new();
        for item in &service_hooks.items {
            if let TraitItem::Fn(method) = item {
                let mut ty = RpcTypes::default();
                syn::visit_mut::VisitMut::visit_signature_mut(&mut ty, &mut method.sig.clone());
                if let (Some(input), Some(output)) = (ty.request, ty.response) {
                    types.insert(
                        method
                            .sig
                            .ident
                            .to_string()
                            .trim_start_matches("r#")
                            .to_string(),
                        (input, output),
                    );
                }
            }
        }
        for (rpc, meta) in methods {
            if meta["client_stream"] == true {
                continue;
            }
            let (input, output) = types
                .get(&rpc.to_snake_case())
                .ok_or("missing Connect message types")?;
            let input = message_path(input, "proto");
            let output = message_path(output, "proto");
            let types = format!("_,{input},<{output} as buffa::HasMessageView>::View<'static>");
            let service = format!("{name}Service");
            let args = format!(
                "client,config,{service:?},{rpc:?},serde_json::from_value(request)?,Default::default()"
            );
            let action = if meta["server_stream"] == true {
                format!(
                    "let mut stream=call_server_stream::<{types}>({args}).await?;while let Some(msg)=stream.message::<{output}>().await?{{emit(serde_json::to_value(msg.to_owned_message())?)?;}}"
                )
            } else {
                format!(
                    "let res=call_unary::<{types}>({args}).await?;emit(serde_json::to_value(res.into_owned())?)?;"
                )
            };
            writeln!(commands, "({name:?},{rpc:?})=>{{{action}}},")?;
        }
        // Framework-owned services need the account and administrative policies
        // specific to those services before exposing them on a public router.
        let notification = policy["notification"] == true;
        let own = policy["entity"]["own"].as_str();
        if own.is_some_and(|v| {
            !matches!(
                v,
                "OWN_HOLDER" | "OWN_TENANT" | "OWN_EVENT" | "OWN_FACT" | "OWN_AUDIT" | "OWN_ACCESS"
            )
        }) {
            continue;
        }
        let svc = format!("crate::services::{}::{short}Service", module(package));
        let local = format!("sink_{}", name.replace('.', "__").to_snake_case());
        writeln!(
            out,
            "mod {local} {{\nuse super::*;\npub struct Sink(pub Database);\n#[allow(refining_impl_trait)]\nimpl<N: {svc}> {svc}Layer<N> for Sink {{"
        )?;
        for rpc in methods.keys() {
            if own.is_some_and(|owner| match owner {
                "OWN_HOLDER" => false,
                "OWN_TENANT" => matches!(rpc.as_str(), "Add" | "AddMany" | "Erase"),
                _ => !matches!(rpc.as_str(), "Get" | "List" | "Memberships"),
            }) {
                continue;
            }
            if !notification
                && !matches!(
                    rpc.as_str(),
                    "Memberships"
                        | "Add"
                        | "AddMany"
                        | "Get"
                        | "Patch"
                        | "Apply"
                        | "Erase"
                        | "List"
                        | "Watch"
                )
            {
                continue;
            }
            let fun = rpc.to_snake_case();
            let (input, output) = types.get(&fun).ok_or("missing sink message types")?;
            let input = message_path(input, "crate::proto");
            let output = message_path(output, "crate::proto");
            if rpc == "Listen" && notification {
                writeln!(
                    out,
                    "async fn listen(&self,_:&N,ctx:RequestContext,request:ServiceRequest<'_,{input}>)->ServiceResult<::connectrpc::ServiceStream<{output}>> {{self.0.listen(ctx,{name:?},&request.to_owned_message()).await}}"
                )?;
                continue;
            }
            if rpc == "Watch" {
                writeln!(
                    out,
                    "async fn watch(&self,_:&N,ctx:RequestContext, request:ServiceRequest<'_,{input}>) -> ServiceResult<::connectrpc::ServiceStream<{output}>> {{self.0.watch(ctx,{name:?},&request.to_owned_message()).await}}"
                )?;
                continue;
            }

            writeln!(
                out,
                "async fn {fun}(&self, _: &N, ctx: RequestContext, request: ServiceRequest<'_, {input}>) -> ServiceResult<{output}> {{\nResponse::ok(self.0.rpc(&ctx, {name:?}, {rpc:?}, &request.to_owned_message()).await?)\n}}"
            )?;
        }
        writeln!(out, "}}")?;
        let mut gate = String::new();
        let mut audit = String::new();
        let mut calls = String::new();
        for item in &service_hooks.items {
            let TraitItem::Fn(f) = item else { continue };
            let fun = &f.sig.ident;
            let snake = fun.to_string();
            let (rpc, method) = methods
                .iter()
                .find(|(rpc, _)| rpc.to_snake_case() == snake.trim_start_matches("r#"))
                .ok_or("unmapped RPC")?;
            let sig = crate::layers::concrete_signature(f.sig.clone()).to_token_stream();
            let direct = method["policy"].get("direct").is_some();
            let action = format!("/{name}Service/{rpc}");
            let arg = match f.sig.inputs.last() {
                Some(syn::FnArg::Typed(arg)) => arg.pat.to_token_stream(),
                _ => return Err("missing request".into()),
            };
            let deployment_only = match own {
                Some("OWN_HOLDER") | None => false,
                Some("OWN_TENANT") => matches!(rpc.as_str(), "Add" | "AddMany" | "Erase"),
                Some(_) => {
                    !matches!(rpc.as_str(), "Get" | "List")
                        && method["policy"].get("account").is_none()
                }
            };
            if matches!(own, Some("OWN_EVENT" | "OWN_FACT"))
                && matches!(
                    rpc.as_str(),
                    "Add" | "AddMany" | "Patch" | "Apply" | "Erase"
                )
            {
                let (_, output) = types.get(&snake).ok_or("missing history response")?;
                let output = message_path(output, "crate::proto");
                writeln!(
                    gate,
                    "{sig} {{let _=(next,ctx,{arg});async move {{ Err::<connectrpc::Response<{output}>,_>(connectrpc::ConnectError::permission_denied(\"a past is written by the past package\")) }} }}"
                )?;
                continue;
            }
            if deployment_only {
                writeln!(
                    gate,
                    "{sig} {{let _=next;{svc}::{fun}(&{svc}Unimplemented,ctx,{arg})}}"
                )?;
                continue;
            }
            let account = method["policy"].get("account").is_some();
            let authorize = if rpc == "AddMany"
                && method["input"]
                    .as_str()
                    .is_some_and(|input| input.ends_with("AddManyRequest"))
            {
                format!(
                    "authorize_cost(ctx,{name:?},{rpc:?},self.public.contains(&{action:?}),{direct},{account},{arg}.items.len())"
                )
            } else {
                format!(
                    "authorize(ctx,{name:?},{rpc:?},self.public.contains(&{action:?}),{direct},{account})"
                )
            };
            let capture = if method["client_stream"] == true {
                String::new()
            } else {
                format!("let ctx=Database::presence_request(ctx,||{arg}.to_owned_message())?;")
            };
            let input = method["input"]
                .as_str()
                .ok_or("missing input")?
                .trim_start_matches('.');
            let output = method["output"]
                .as_str()
                .ok_or("missing output")?
                .trim_start_matches('.');
            let mut call_types = RpcTypes::default();
            syn::visit_mut::VisitMut::visit_signature_mut(&mut call_types, &mut f.sig.clone());
            let result_ty = message_path(
                &call_types.response.ok_or("missing access output")?,
                "crate::proto",
            );
            let download = method["policy"].get("download").is_some();
            let request = if method["client_stream"] == true {
                "Ok(serde_json::Value::Null)".into()
            } else {
                format!(
                    "serde_json::to_value({arg}.to_owned_message()).map_err(|_|connectrpc::ConnectError::invalid_argument(\"invalid access request\"))"
                )
            };
            let finish = if method["server_stream"] == true {
                format!(
                    "Ok(response.map_body(|body|attempt.stream::<{result_ty},_>(self.db.clone(),Database::enforce_presence(&ctx,body))))"
                )
            } else {
                format!(
                    "attempt.output::<{result_ty},_>(&self.db,&response.body).await?; Ok(response)"
                )
            };
            writeln!(
                gate,
                "{sig} {{async move {{{capture}let mut ctx=ctx;let attempt=crate::transport::access::Attempt::start(&mut ctx,{input:?},{output:?},{action:?},{download},||{request})?; let ctx=match self.db.{authorize}.await{{Ok(c)=>c, Err(e)=>return Err(attempt.failed(&self.db,e).await)}}; let response=match next.{fun}(ctx.clone(),{arg}).await{{Ok(v)=>v,Err(e)=>return Err(attempt.failed(&self.db,e).await)}};{finish}}}}}"
            )?;
            if method["server_stream"] == false && method["client_stream"] == false {
                writeln!(
                    audit,
                    "{sig} {{async move {{let mut ctx=ctx;let guard=self.0.begin_request(&mut ctx,{name:?},{rpc:?},||{arg}.to_owned_message()).await?;let result=next.{fun}(ctx,{arg}).await;if let Some(guard)=guard {{guard.finish(result.is_ok()).await?;}} result}}}}"
                )?;
                let (input, output) = types
                    .get(&rpc.to_snake_case())
                    .ok_or("missing Core message types")?;
                let input = message_path(input, "crate::proto");
                let output = message_path(output, "crate::proto");
                let method_name = format!("{}_owned", snake.trim_start_matches("r#"));
                if rpc == "List" && policy["entity"].get("list").is_some() {
                    let row = format!("crate::proto::{}::{short}", module(package));
                    writeln!(calls, "fn list_all<'a>(&'a self,ctx:&'a RequestContext,request:&{input})->impl ::paydirt::page::Stream<Item=Result<{row},::connectrpc::ConnectError>> + 'a {{
                       ::paydirt::page::all(request,|q| &mut q.after,move |q|async move {{let page=self.list_owned(ctx,q).await?;Ok((page.items,page.next))}},||::connectrpc::ConnectError::internal(\"repeated continuation token\"))
                    }}")?;
                }
                writeln!(calls,"async fn {method_name}(&self, ctx: &RequestContext, req: {input})-> Result<{output}, ::connectrpc::ConnectError> {{
                    use buffa::{{Message,HasMessageView}}; use connectrpc::Encodable;
                    let bytes=req.encode_to_bytes();
                    let view={input}::decode_view(&bytes).map_err(|_|connectrpc::ConnectError::internal(\"invalid downstream request\"))?;
                    let reply=self.{fun}(ctx.clone(),ServiceRequest::from_parts(&view,&bytes)).await?;
                    let wire=reply.body.encode(connectrpc::CodecFormat::Proto)?;
                    {output}::decode_from_slice(&wire).map_err(|_|connectrpc::ConnectError::internal(\"invalid downstream response\"))
                }}")?;
            }
        }
        writeln!(
            out,
            "impl<N:{svc}> {svc}Layer<N> for Gate {{{gate}}} impl<N:{svc}> {svc}Layer<N> for Audit {{{audit}}} }}"
        )?;
        writeln!(
            adapters,
            "#[allow(async_fn_in_trait)] pub trait {short}Calls:{svc} {{ {calls} }} impl<N:{svc}> {short}Calls for N {{}}"
        )?;

        let layer = name.replace('.', "__").to_snake_case();
        writeln!(
            next_methods,
            "pub fn {layer}(&self)->impl {svc} {{ {svc}Overlay {{ next:{svc}Unimplemented,layer:{local}::Sink(self.0.clone()) }} }}"
        )?;
        writeln!(
            layers,
            "fn {layer}(&self, next: impl {svc}) -> impl {svc} {{ next }}"
        )?;
        let install = if matches!(own, Some("OWN_AUDIT" | "OWN_ACCESS")) {
            "crate::transport::access::OPTIONS.reads"
        } else {
            "true"
        };
        writeln!(
            mount,
            "let router=if {install} {{let core=layers.{layer}(next.{layer}()); let core={svc}Overlay{{next:core,layer:interceptors.clone()}}; let audit={svc}Overlay{{next:core,layer:Audit(db.clone())}}; let gate={svc}Overlay{{next:audit,layer:Gate{{db:db.clone(),public:layers.public_methods()}}}}; {svc}Ext::register(::std::sync::Arc::new(gate),router)}}else{{router}};"
        )?;
    }
    writeln!(
        out,
        "struct Gate {{db:Database,public:&'static [&'static str]}} struct Audit(Database); #[derive(Clone)] pub struct Next(pub Database); impl Next {{ {next_methods} }} {adapters} pub trait Layers {{fn interceptors(&self)->crate::storage::intercept::Layer {{Default::default()}} fn public_methods(&self)->&'static [&'static str] {{&[]}} {layers}}} pub fn mount(router: Router, db: Database, layers: &impl Layers) -> Router {{let next=Next(db.clone()); let interceptors=layers.interceptors().public(); {mount}router}}"
    )?;
    let command_file = format!(
        "async fn dispatch(client:&HttpClient,config:&ClientConfig,entity:&str,rpc:&str,request:Value,mut emit:impl FnMut(Value)->Result<()>)->Result<()>{{use connectrpc::client::{{call_unary,call_server_stream}};match (entity,rpc) {{{commands} _=>return Err(\"unsupported command\".into())}}Ok(())}}"
    );
    fs::write(
        root.join("commands.rs"),
        prettyplease::unparse(&syn::parse_file(&command_file)?),
    )?;
    let syntax = syn::parse_file(&out)?;
    fs::write(root.join("sinks.rs"), prettyplease::unparse(&syntax))?;
    Ok(())
}

// Match Payday's resource-only composition: providers own their source and
// authorization, and registering a computed value does not require a database.
fn resource_providers(work: &Path, root: &Path) -> Result<()> {
    let descriptor: Value = serde_json::from_slice(&fs::read(work.join("resolved.json"))?)?;
    let mut layers = String::new();
    let mut mount = String::new();
    for file in descriptor["file"].as_array().ok_or("missing files")? {
        let package = file["package"].as_str().unwrap_or_default();
        for message in file["messageType"].as_array().into_iter().flatten() {
            if message["options"].get("[payday.resource]").is_none() {
                continue;
            }
            let short = message["name"]
                .as_str()
                .ok_or("missing read resource name")?;
            let svc = format!("crate::services::{}::{short}Service", module(package));
            let provider = format!("{}_{}", package.replace('.', "__"), short).to_snake_case();
            writeln!(
                layers,
                "fn {provider}(&self) -> impl {svc} {{ {svc}Unimplemented }}"
            )?;
            writeln!(
                mount,
                "let router={svc}Ext::register(::std::sync::Arc::new(layers.{provider}()),router);"
            )?;
        }
    }
    let source = format!(
        "// @generated by paydirt.\npub trait Layers {{ {layers} }} pub fn mount(router: ::connectrpc::Router, layers: &impl Layers) -> ::connectrpc::Router {{ {mount} router }}"
    );
    fs::write(
        root.join("sinks.rs"),
        prettyplease::unparse(&syn::parse_file(&source)?),
    )?;
    Ok(())
}
