use crate::Result;
use heck::ToSnakeCase;
use quote::ToTokens;
use serde_json::Value;
use std::{collections::BTreeMap, fmt::Write, fs, path::Path};
use syn::{Item, TraitItem};

fn ident(s: &str) -> String {
    match s {
        "self" | "super" | "Self" | "crate" => format!("{s}_"),
        _ => format!("r#{s}"),
    }
}
fn module(path: &str) -> String {
    path.split('.').map(ident).collect::<Vec<_>>().join("::")
}
pub fn generate(work: &Path) -> Result<()> {
    let root = work.join("generated/storage");
    let policies: BTreeMap<String, Value> =
        serde_json::from_slice(&fs::read(root.join("policies.json"))?)?;
    let mut out = String::from(
        "// @generated by paydirt.\nuse crate::transport::Database;\nuse ::connectrpc::{RequestContext, Response, Router, ServiceRequest, ServiceResult};\n",
    );
    let mut hooks = BTreeMap::new();
    for entry in fs::read_dir(work.join("generated/services"))? {
        let path = entry?.path();
        let Some(file) = path
            .file_name()
            .and_then(|n| n.to_str())
            .filter(|n| n.ends_with(".__layers.rs"))
        else {
            continue;
        };
        let package = file.rsplit_once('.').unwrap().0;
        for item in syn::parse_file(&fs::read_to_string(&path)?)?.items {
            if let Item::Trait(t) = item {
                hooks.insert((package.to_string(), t.ident.to_string()), t);
            }
        }
    }
    let mut next_methods = String::new();
    let mut adapters = String::new();
    let mut layers = String::new();
    let mut mount = String::new();
    for (name, policy) in policies {
        let methods = policy["methods"].as_object().ok_or("missing methods")?;
        // Framework-owned services need the account and administrative policies
        // specific to those services before exposing them on a public router.
        if policy["entity"].get("own").is_some() || methods.is_empty() {
            continue;
        }
        let (package, short) = name
            .rsplit_once('.')
            .ok_or("expected application package")?;
        let svc = format!("crate::services::{}::{short}Service", module(package));
        let local = format!("sink_{}", name.replace('.', "__").to_snake_case());
        writeln!(
            out,
            "mod {local} {{\nuse super::*;\npub struct Sink(pub Database);\n#[allow(refining_impl_trait)]\nimpl<N: {svc}> {svc}Layer<N> for Sink {{"
        )?;
        for (rpc, method) in methods {
            if !matches!(
                rpc.as_str(),
                "Add" | "AddMany" | "Get" | "Patch" | "Apply" | "Erase" | "List" | "Watch"
            ) {
                continue;
            }
            let message = |field: &str| -> Result<String> {
                Ok(format!(
                    "crate::proto::{}",
                    module(
                        method[field]
                            .as_str()
                            .ok_or("missing RPC type")?
                            .trim_start_matches('.')
                    )
                ))
            };
            let input = message("input")?;
            let output = message("output")?;
            let fun = rpc.to_snake_case();
            if rpc == "Watch" {
                writeln!(
                    out,
                    "async fn watch(&self,_:&N,ctx:RequestContext, request:ServiceRequest<'_,{input}>) -> ServiceResult<::connectrpc::ServiceStream<{output}>> {{self.0.watch(ctx,{name:?},&request.to_owned_message()).await}}"
                )?;
                continue;
            }

            writeln!(
                out,
                "async fn {fun}(&self, _: &N, ctx: RequestContext, request: ServiceRequest<'_, {input}>) -> ServiceResult<{output}> {{\nResponse::ok(self.0.rpc(&ctx, {name:?}, {rpc:?}, &request.to_owned_message()).await?)\n}}"
            )?;
        }
        writeln!(out, "}}")?;
        let hook_name = format!("{short}ServiceLayer");
        let mut available = hooks
            .iter()
            .filter(|((file, ty), _)| ty == &hook_name && file.starts_with(&format!("{package}.")));
        let hooks = &available.next().ok_or("missing generated layer")?.1;
        if available.next().is_some() {
            return Err(format!("ambiguous generated layer for {name}").into());
        }
        let mut gate = String::new();
        let mut audit = String::new();
        let mut calls = String::new();
        for item in &hooks.items {
            let TraitItem::Fn(f) = item else { continue };
            let fun = &f.sig.ident;
            let snake = fun.to_string();
            let (rpc, method) = methods
                .iter()
                .find(|(rpc, _)| rpc.to_snake_case() == snake.trim_start_matches("r#"))
                .ok_or("unmapped RPC")?;
            let sig = crate::layers::concrete_signature(f.sig.clone()).to_token_stream();
            let direct = method["policy"].get("direct").is_some();
            let action = format!("/{name}Service/{rpc}");
            let arg = match f.sig.inputs.last() {
                Some(syn::FnArg::Typed(arg)) => arg.pat.to_token_stream(),
                _ => return Err("missing request".into()),
            };
            writeln!(
                gate,
                "{sig} {{async move {{let ctx=self.db.authorize(ctx,{name:?},{rpc:?},self.public.contains(&{action:?}),{direct})?;next.{fun}(ctx,{arg}).await}}}}"
            )?;
            if method["server_stream"] == false && method["client_stream"] == false {
                writeln!(
                    audit,
                    "{sig} {{async move {{let mut ctx=ctx;let guard=self.0.begin(&mut ctx).await?;let result=next.{fun}(ctx,{arg}).await;if let Some(guard)=guard {{guard.finish(result.is_ok()).await?;}} result}}}}"
                )?;
                let input = module(method["input"].as_str().unwrap().trim_start_matches('.'));
                let output = module(method["output"].as_str().unwrap().trim_start_matches('.'));
                let method_name = format!("{}_owned", snake.trim_start_matches("r#"));
                writeln!(calls,"async fn {method_name}(&self, ctx: &RequestContext, req:crate::proto::{input})-> Result<crate::proto::{output}, ::connectrpc::ConnectError> {{
                    use buffa::{{Message,HasMessageView}}; use connectrpc::Encodable;
                    let bytes=req.encode_to_bytes();
                    let view=crate::proto::{input}::decode_view(&bytes).map_err(|_|connectrpc::ConnectError::internal(\"invalid downstream request\"))?;
                    let reply=self.{fun}(ctx.clone(),ServiceRequest::from_parts(&view,&bytes)).await?;
                    let wire=reply.body.encode(connectrpc::CodecFormat::Proto)?;
                    crate::proto::{output}::decode_from_slice(&wire).map_err(|_|connectrpc::ConnectError::internal(\"invalid downstream response\"))
                }}")?;
            }
        }
        writeln!(
            out,
            "impl<N:{svc}> {svc}Layer<N> for Gate {{{gate}}} impl<N:{svc}> {svc}Layer<N> for Audit {{{audit}}} }}"
        )?;
        writeln!(
            adapters,
            "#[allow(async_fn_in_trait)] pub trait {short}Calls:{svc} {{ {calls} }} impl<N:{svc}> {short}Calls for N {{}}"
        )?;

        let layer = name.replace('.', "__").to_snake_case();
        writeln!(
            next_methods,
            "pub fn {layer}(&self)->impl {svc} {{ {svc}Overlay {{ next:{svc}Unimplemented,layer:{local}::Sink(self.0.clone()) }} }}"
        )?;
        writeln!(
            layers,
            "fn {layer}(&self, next: impl {svc}) -> impl {svc} {{ next }}"
        )?;
        writeln!(
            mount,
            "let core=layers.{layer}(next.{layer}()); let audit={svc}Overlay{{next:core,layer:Audit(db.clone())}}; let gate={svc}Overlay{{next:audit,layer:Gate{{db:db.clone(),public:layers.public_methods()}}}}; let router={svc}Ext::register(::std::sync::Arc::new(gate),router);"
        )?;
    }
    writeln!(
        out,
        "struct Gate {{db:Database,public:&'static [&'static str]}} struct Audit(Database); #[derive(Clone)] pub struct Next(pub Database); impl Next {{ {next_methods} }} {adapters} pub trait Layers {{fn public_methods(&self)->&'static [&'static str] {{&[]}} {layers}}} pub fn mount(router: Router, db: Database, layers: &impl Layers) -> Router {{let next=Next(db.clone()); {mount}router}}"
    )?;
    let syntax = syn::parse_file(&out)?;
    fs::write(root.join("sinks.rs"), prettyplease::unparse(&syntax))?;
    Ok(())
}
